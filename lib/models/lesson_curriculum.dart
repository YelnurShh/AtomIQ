      ),
    ..._advancedTheory,
  ];

  static final List<ChemistryLesson> practice = [
    for (var i = 0; i < _practiceSpecs.length; i++)
      _practiceSpecs[i].toLesson(),
  ];

  static List<LessonQuestion> _questions(String rows) => rows
      .trim()
      .split('\n')
      .asMap()
      .entries
      .map((entry) {
        final p = entry.value.split('|');
        final correctIndex = entry.key % 3;
        final options = switch (correctIndex) {
          0 => [p[1], p[2], p[3]],
          1 => [p[2], p[1], p[3]],
          _ => [p[2], p[3], p[1]],
        };
        return LessonQuestion(
          text: p[0],
          options: options,
          correctIndex: correctIndex,
          explanation: p[4],
        );
      })
      .toList(growable: false);

