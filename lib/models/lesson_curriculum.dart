class _PracticeSpec {
  const _PracticeSpec(
    this.id,
    this.grade,
    this.title,
    this.summary,
    this.notes,
    this.examples,
    this.matches,
    this.quiz,
  );
  final String id;
  final int grade;
  final String title;
  final String summary;
  final List<String> notes;
  final List<LessonWorkedExample> examples;
  final List<LessonMatch> matches;
  final String quiz;

  ChemistryLesson toLesson() {
    final questions = quiz
        .trim()
        .split('\n')
        .asMap()
        .entries
        .map((entry) {
          final p = entry.value.split('|');
          // Rotate the correct option so students cannot guess from position.
          final order = entry.key % 3;
          final options = switch (order) {
            0 => [p[1], p[2], p[3]],
            1 => [p[2], p[1], p[3]],
            _ => [p[2], p[3], p[1]],
          };
          return LessonQuestion(
            text: p[0],
            options: options,
            correctIndex: order,
            explanation: p[4],
          );
        })
        .toList(growable: false);
    return ChemistryLesson(
      id: 'practice_$id',
      title: title,
      summary: summary,
      concepts: notes,
      exampleTitle: 'Мысал есеп',
      example: examples.first.answer,
      questions: questions,
      matches: matches,
      grade: grade,
      practice: true,
      workedExamples: examples,
    );
  }
}
