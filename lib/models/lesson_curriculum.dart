    required String summary,
    required List<String> notes,
    required List<LessonWorkedExample> examples,
    required String quiz,
    required List<LessonMatch> matches,
  }) => ChemistryLesson(
    id: 'theory_$id',
    title: title,
    summary: summary,
    concepts: notes,
    exampleTitle: 'Мысал есеп',
    example: examples.first.answer,
    questions: _questions(quiz),
    matches: matches,
    grade: grade,
    workedExamples: examples,
  );

