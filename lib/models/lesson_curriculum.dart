    for (var i = 0; i < LessonCatalog.lessons.length; i++)
      LessonCatalog.lessons[i].copyWith(
        grade: i < 4 ? 7 : 8,
        concepts: [...LessonCatalog.lessons[i].concepts, _foundationNotes[i]],
        questions: [
          ...LessonCatalog.lessons[i].questions,
          ..._questions(_foundationQuestions[i]),
        ],
        workedExamples: [
          LessonWorkedExample(
            question: _foundationPrompts[i],
